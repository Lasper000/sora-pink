/**
 * แปลงรหัสไปรษณีย์ไทย (5 หลัก) เป็นชื่อจังหวัดโดยอัตโนมัติ (รองรับรหัสพิเศษ เช่น 10270/10540 สมุทรปราการ)
 */
export function resolveProvinceFromPostalCode(postalCode: string): string | null {
  const digits = postalCode.replace(/\D/g, '');
  if (digits.length !== 5) return null;

  const code = Number(digits);
  // Samut Prakan shares 10xxx range (10130, 10270, 10280, 10290, 10540-10570)
  if (
    code === 10130 ||
    code === 10270 ||
    code === 10280 ||
    code === 10290 ||
    (code >= 10540 && code <= 10570)
  ) {
    return 'สมุทรปราการ';
  }

  return POSTAL_PREFIX_TO_PROVINCE[digits.slice(0, 2)] || null;
}

const SAVED_ADDRESSES_KEY = 'sora_saved_addresses_v1';

export function getSavedAddresses(userId?: string): SavedAddress[] {
  try {
    const raw = localStorage.getItem(`${SAVED_ADDRESSES_KEY}_${userId || 'guest'}`);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveAddressToBook(address: Omit<SavedAddress, 'id'>, userId?: string): SavedAddress[] {
  const list = getSavedAddresses(userId);
  const newItem: SavedAddress = {
    ...address,
    id: 'addr-' + Date.now(),
  };
  const updated = address.isDefault
    ? [newItem, ...list.map((a) => ({ ...a, isDefault: false }))]
    : [newItem, ...list];
  try {
    localStorage.setItem(`${SAVED_ADDRESSES_KEY}_${userId || 'guest'}`, JSON.stringify(updated.slice(0, 6)));
  } catch {
    // ignore storage limits
  }
  return updated.slice(0, 6);
}

export function deleteAddressFromBook(id: string, userId?: string): SavedAddress[] {
  const list = getSavedAddresses(userId).filter((a) => a.id !== id);
  try {
    localStorage.setItem(`${SAVED_ADDRESSES_KEY}_${userId || 'guest'}`, JSON.stringify(list));
  } catch {
    // ignore
  }
  return list;
}
